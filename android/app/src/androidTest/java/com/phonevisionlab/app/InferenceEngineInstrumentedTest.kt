            InstrumentationRegistry.getInstrumentation().waitForIdleSync()
            scenario.onActivity { activity ->
                val control = activity.findViewById<View>(R.id.stopControlButton)
                assertTrue("底部硬件按钮应能滚动到可见区域", control.getGlobalVisibleRect(Rect()))
            }
        }
    }
