    @Test
    fun controllerResponseMustMatchTheSentRequest() {
        val server = ServerSocket(0)
        val worker = thread(isDaemon = true) {
            server.accept().use { socket ->
                socket.soTimeout = 5000
                val input = socket.getInputStream().bufferedReader()
                var contentLength = 0
                while (true) {
                    val line = input.readLine() ?: break
                    if (line.isEmpty()) break
                    if (line.startsWith("Content-Length:", ignoreCase = true)) {
                        contentLength = line.substringAfter(':').trim().toInt()
                    }
                }
                val body = CharArray(contentLength)
                var read = 0
                while (read < body.size) {
                    val n = input.read(body, read, body.size - read)
                    if (n < 0) break
                    read += n
                }
                val json = "{\"requestId\":\"different-id\",\"status\":\"executed\"}"
                val reply = "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n" +
                    "Content-Length: ${json.toByteArray().size}\r\nConnection: close\r\n\r\n$json"
                socket.getOutputStream().write(reply.toByteArray())
            }
        }
        val adapter = DeviceAdapter("127.0.0.1", server.localPort, timeoutMs = 3000, maxRetries = 0)
        try {
            val result = adapter.send(ControlProtocol.ACTION_LED_ON, "led0", requestId = "expected-id")
            assertEquals(ControlProtocol.CommandStatus.FAILED, result.status)
            assertTrue(result.message.contains("编号不匹配"))
            adapter.disconnect()
            val afterDisconnect = adapter.send(ControlProtocol.ACTION_LED_ON, "led0")
            assertEquals(ControlProtocol.CommandStatus.FAILED, afterDisconnect.status)
        } finally {
            adapter.disconnect()
            server.close()
            worker.join(5000)
        }
    }

    @Test
    fun importedModelRetainsItsOwnNormalizationValues() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val context = instrumentation.targetContext
        val archive = File(context.cacheDir, "qa-custom-preprocess.zip")
        val manifest = """{
          "format_version":1,
          "model":{"file":"model.tflite",
                   "input":{"shape":[1,4,4,3]},
                   "output":{"shape":[1,2],"interpretation":"probabilities"}},
          "preprocess":{"input_size":4,"layout":"NHWC","color_order":"RGB",
                        "normalization":"imagenet","center_crop":true,
                        "contract_version":1,"mean":[0.1,0.2,0.3],"std":[1,2,3]}
        }""".trimIndent()
        val labels = """{"index_to_name":{"0":"red","1":"green"}}"""
        ZipOutputStream(archive.outputStream()).use { zip ->
            fun entry(name: String, bytes: ByteArray) {
                zip.putNextEntry(ZipEntry(name))
                zip.write(bytes)
                zip.closeEntry()
            }
            entry("manifest.json", manifest.toByteArray())
            entry("labels.json", labels.toByteArray())
            entry("model.tflite", instrumentation.context.assets.open("pvl-test.tflite").use { it.readBytes() })
        }
        var importedId: String? = null
        try {
            val result = ModelPackage.importFromZip(context, archive.absolutePath)
            assertTrue(result is ModelPackage.ImportResult.Success)
            importedId = (result as ModelPackage.ImportResult.Success).model.id
            val loaded = ModelPackage.load(context, importedId)
            assertNotNull(loaded)
            assertArrayEquals(floatArrayOf(0.1f, 0.2f, 0.3f), loaded!!.spec.mean.toFloatArray(), 0.00001f)
            assertArrayEquals(floatArrayOf(1f, 2f, 3f), loaded.spec.std.toFloatArray(), 0.00001f)
            val bitmap = Bitmap.createBitmap(4, 4, Bitmap.Config.ARGB_8888)
            try {
                bitmap.eraseColor(Color.rgb(255, 255, 255))
                val values = Preprocessor(loaded.spec).process(bitmap)
                assertArrayEquals(floatArrayOf(0.9f, 0.4f, 0.7f / 3f), values.copyOfRange(0, 3), 0.00001f)
            } finally {
                bitmap.recycle()
            }
        } finally {
            importedId?.let { ModelPackage.deleteImported(context, it) }
            archive.delete()
        }
    }

    @Test
    fun invalidModelBytesAreRejectedBeforeImportIsRecorded() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val archive = File(context.cacheDir, "qa-invalid-model.zip")
        val manifest = """{"format_version":1,
          "model":{"file":"model.tflite","input":{"shape":[1,4,4,3]},
                   "output":{"shape":[1,2],"interpretation":"probabilities"}},
          "preprocess":{"input_size":4,"layout":"NHWC","color_order":"RGB",
                        "normalization":"raw","center_crop":true,"contract_version":1}}
        """.trimIndent()
        ZipOutputStream(archive.outputStream()).use { zip ->
            fun entry(name: String, bytes: ByteArray) {
                zip.putNextEntry(ZipEntry(name))
                zip.write(bytes)
                zip.closeEntry()
            }
            entry("manifest.json", manifest.toByteArray())
            entry("labels.json", """{"index_to_name":{"0":"a","1":"b"}}""".toByteArray())
            entry("model.tflite", ByteArray(2048))
        }
        try {
            val before = ModelPackage.listImported(context).size
            val result = ModelPackage.importFromZip(context, archive.absolutePath)
            assertTrue(result is ModelPackage.ImportResult.Failure)
            assertEquals(before, ModelPackage.listImported(context).size)
        } finally {
            archive.delete()
        }
    }

