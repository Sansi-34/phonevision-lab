    @Test
    fun resizedPixelsMatchThePcTrainingContract() {
        // Expected values were generated by pc-client/pvl_preprocess.py from
        // this non-square image, including its area-based downsampling.
        val bitmap = Bitmap.createBitmap(8, 6, Bitmap.Config.ARGB_8888)
        try {
            for (y in 0 until 6) for (x in 0 until 8) {
                bitmap.setPixel(x, y, Color.rgb(x * 30, y * 40, (x + y) * 15))
            }
            val expected = floatArrayOf(
                15f,20f,15f, 60f,20f,38f, 105f,20f,60f, 150f,20f,83f,
                15f,80f,38f, 60f,80f,60f, 105f,80f,83f, 150f,80f,105f,
                15f,120f,53f, 60f,120f,75f, 105f,120f,98f, 150f,120f,120f,
                15f,180f,75f, 60f,180f,98f, 105f,180f,120f, 150f,180f,143f,
            )
            val result = Preprocessor(PreprocessSpec.Spec(inputSize = 4, normalization = "raw"))
                .process(bitmap)
            assertArrayEquals(expected, result, 0.001f)
        } finally {
            bitmap.recycle()
        }
    }

