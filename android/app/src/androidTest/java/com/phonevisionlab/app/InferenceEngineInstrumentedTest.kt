/** Runs the real TFLite Java/Android path with a deterministic synthetic model. */
@RunWith(AndroidJUnit4::class)
class InferenceEngineInstrumentedTest {
    private fun fixture(): File {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val model = File(instrumentation.targetContext.cacheDir, "qa-inference.tflite")
        instrumentation.context.assets.open("pvl-test.tflite").use { input ->
            model.outputStream().use { output -> input.copyTo(output) }
        }
        return model
    }

    @Test
    fun predictsUsingTheActualTfliteTensorBuffers() {
        val engine = InferenceEngine(
            modelPath = fixture().absolutePath,
            spec = PreprocessSpec.Spec(inputSize = 4, normalization = "raw"),
            labels = listOf("red", "green"),
            displayLabels = listOf("Red", "Green"),
        )
        val bitmap = Bitmap.createBitmap(4, 4, Bitmap.Config.ARGB_8888)
        try {
            bitmap.eraseColor(Color.rgb(200, 0, 0))
            val red = engine.run(bitmap)
            assertNotNull(red)
            assertEquals("red", red!!.topLabel)
            assertTrue(red.confidence > 0.99f)
            bitmap.eraseColor(Color.rgb(0, 200, 0))
            val green = engine.run(bitmap)
            assertNotNull(green)
            assertEquals("green", green!!.topLabel)
            assertEquals(2L, engine.completedFrames())
        } finally {
            engine.close()
            bitmap.recycle()
        }
    }

